        let ultimoPoema =
            "";

        let contador =
            0;


        function sortear(lista) {

            return lista[
                Math.floor(
                    Math.random() *
                    lista.length
                )
            ];

        }


        function montarPoema() {

            const partes =
                biblioteca[
                    categoriaAtual
                ];


            return `
${sortear(partes.inicio)}
${sortear(partes.segundo)}
${sortear(partes.terceiro)}

${sortear(partes.quarto)}
${sortear(partes.quinto)}
${sortear(partes.final)}
            `.trim();

        }


        function gerarPoema() {

            let novoPoema =
                montarPoema();


            let tentativas = 0;


            while (
                novoPoema === ultimoPoema &&
                tentativas < 20
            ) {

                novoPoema =
                    montarPoema();

                tentativas++;

            }


            ultimoPoema =
                novoPoema;


            poemaElemento.classList.add(
                "sumir"
            );


            setTimeout(
                () => {

                    poemaElemento.textContent =
                        novoPoema;

                    poemaElemento.classList.remove(
                        "sumir"
                    );

                },
                220
            );


            contador++;


            if (
                contadorElemento
            ) {

                contadorElemento.textContent =
                    contador;

            }

        }


